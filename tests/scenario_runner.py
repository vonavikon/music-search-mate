# Typical typos: substitution, insertion, deletion, transposition
TYPO_MAP = {
    "Michael": ["Michal", "Micheal", "Mihael"],
    "Jackson": ["Jacson", "Jeckson", "Jakson"],
    "Billie": ["Billy", "Bille", "Billi"],
    "Jean": ["Jeen", "Gean"],
    "Beatles": ["Beetles", "Beatls", "Betles"],
    "Nirvana": ["Nervana", "Nirvane", "Nirvanna"],
}

TRANSLIT_MAP = {
    "ч": "ch", "ш": "sh", "щ": "sch", "ж": "zh", "ю": "yu", "я": "ya",
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n",
    "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f",
    "х": "h", "ц": "ts", "э": "e", "ы": "y", "ь": "", "ъ": "",
}


class NoisyUserGenerator:
    """Generator of "gray" user errors: typos, transliteration, noise."""

    @staticmethod
    def typos(text: str) -> list[str]:
        """Replace known words with typical typos."""
        variants = [text]
        for correct, typos_list in TYPO_MAP.items():
            if correct.lower() in text.lower():
                for t in typos_list:
                    variants.append(text.replace(correct, t))
        return list(set(variants))

    @staticmethod
    def translit(text: str) -> str:
        """Transliterate Cyrillic into Latin."""
        result = []
        for ch in text:
            lower = ch.lower()
            if lower in TRANSLIT_MAP:
                tr = TRANSLIT_MAP[lower]
                result.append(tr.upper() if ch.isupper() and len(tr) > 1 else tr)
            else:
                result.append(ch)
        return "".join(result)

    @staticmethod
    def noise(text: str) -> list[str]:
        """Add noise: extra spaces, random characters, emoji."""
        return [
            text,
            f"  {text}  ",
            f"пожалуйста, {text}",
            f"{text} 🎵",
            f"{text}...",
            f"хм, {text} наверное",
        ]

    @staticmethod
    def apply_all(text: str) -> list[str]:
        """All transformations at once -> a list of variants."""
        variants = set()
        variants.update(NoisyUserGenerator.typos(text))
        variants.update(NoisyUserGenerator.noise(text))
        if any(ord(c) > 127 for c in text):
            variants.add(NoisyUserGenerator.translit(text))
        variants.add(text)  # the original
        return list(variants)


