def _make_text_update(text: str, user_id: int = 123, chat_id: int = 456) -> Update:
    user = User(id=user_id, is_bot=False, first_name="Test")
    chat = Chat(id=chat_id, type="private")
    entities = None
    if text.startswith("/"):
        entities = [MessageEntity(type=MessageEntity.BOT_COMMAND, offset=0, length=min(len(text), 20))]
    msg = Message(
        message_id=1, date=datetime.now(timezone.utc),
        chat=chat, from_user=user, text=text, entities=entities,
    )
    return Update(update_id=1, message=msg)


