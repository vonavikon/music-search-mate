@dataclass
class RecordedMessage:
    method: str
    kwargs: dict
    text_sent: str = ""

class RecordingRequest(BaseRequest):
    def __init__(self, token: str = "test:token"):
        super().__init__()
        self._token = token
        self.sent: list[RecordedMessage] = []

    async def do_request(self, *args, **kwargs): return 200, b"{}"
    async def _request_wrapper(self, *args, **kwargs): return 200, b"{}"
    async def initialize(self) -> None: pass
    async def shutdown(self) -> None: pass

    @property
    def base_url(self) -> str: return "http://fake-telegram.local/bot"
    @property
    def base_file_url(self) -> str: return "http://fake-telegram.local/file/bot"
    @property
    def token(self) -> str: return self._token

    async def post(self, url: str, request_data=None, read_timeout=None,
                   write_timeout=None, connect_timeout=None, pool_timeout=None):
        endpoint = url.rsplit("/", 1)[-1] if "/" in url else url
        data = {}
        if request_data and hasattr(request_data, "parameters"):
            params = request_data.parameters
            if isinstance(params, dict):
                data = dict(params)
            else:
                for p in params:
                    try: data[p.name] = p.value
                    except Exception: data[p.name] = str(p.value)
        text = str(data.get("text", data.get("caption", "")))
        self.sent.append(RecordedMessage(method=endpoint, kwargs=data, text_sent=text))
        if endpoint == "sendMessage":
            return {"message_id": 999, "date": 1, "chat": {"id": 123, "type": "private"}, "text": text}
        if endpoint == "sendAudio":
            return {"message_id": 1000, "date": 1, "chat": {"id": 123, "type": "private"}, "audio": {"file_id": "fake_audio_id", "duration": 180}}
        if endpoint in ("editMessageText", "editMessageCaption"): return True
        if endpoint == "answerCallbackQuery": return True
        if endpoint == "getMe":
            return {"id": 123456, "is_bot": True, "first_name": "TestBot", "username": "test_bot"}
        return True

    def texts(self) -> list[str]:
        return [m.text_sent for m in self.sent if m.text_sent]

    def methods(self) -> list[str]:
        return [m.method for m in self.sent]

