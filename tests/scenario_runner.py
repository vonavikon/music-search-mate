def _parse_args():
    ap = argparse.ArgumentParser(description="LLM-driven scenario test runner")
    ap.add_argument("--level", choices=["smoke", "regression", "exploration"], default="smoke",
                    help="Уровень тестирования (default: smoke). smoke=Gate1+мало вариаций, regression=оба гейта+семена, exploration=фаззинг")
    ap.add_argument("--gate", choices=["1", "2", "both"], default="both",
                    help="Какие ворота прогонять (default: both; level переопределяет)")
    ap.add_argument("--scenario", default=None,
                    help="ID сценария или префикс (J1, J1-A1, J2-A). Без аргумента — все.")
    ap.add_argument("--variations", type=int, default=None,
                    help="Количество вариаций на сценарий (default: от уровня)")
    ap.add_argument("--dry-run", action="store_true",
                    help="Только генерация — показать что сгенерировано, без прогона")
    ap.add_argument("--no-judge", action="store_true",
                    help="Без LLM-judge (только детерминированные проверки)")
    ap.add_argument("--metamorphic", action="store_true",
                    help="Запустить метаморфические тесты после основных")
    ap.add_argument("--golden", action="store_true",
                    help="Прогнать golden traffic suite (реальные прод-запросы)")
    ap.add_argument("--replay", default=None,
                    help="Путь к файлу с записанными апдейтами для replay")
    ap.add_argument("--model", default="deepseek-v4-flash",
                    help="Модель для генератора и judge (default: deepseek-v4-flash)")
    ap.add_argument("--verbose", "-v", action="store_true")
    return ap.parse_args()


# Test levels: (gate, variations, use_seeds, gate2_for_all)
LEVEL_CONFIG = {
    "smoke":        ("1",    3, False, False),
    "regression":   ("both", 5, True,  True),
    "exploration":  ("both", 10, True, True),
}


async def _main():
    args = _parse_args()
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.WARNING,
                        format="%(levelname)s %(name)s: %(message)s")

    # Apply the level
    level_gate, level_variations, use_seeds, gate2_all = LEVEL_CONFIG[args.level]
    gate = args.gate if args.gate != "both" or args.level == "smoke" else level_gate
    if args.gate == "both" and args.level != "regression":
        gate = level_gate  # the level overrides the default gate
    variations = args.variations if args.variations is not None else level_variations

    # scenario filter
    selected = SCENARIOS
    if args.scenario:
        selected = [s for s in SCENARIOS
                    if s.id == args.scenario or s.id.startswith(args.scenario)]
        if not selected:
            print(f"Сценарий не найден: {args.scenario}")
            return

    # Load seeds if needed
    seeds = _load_seeds() if use_seeds else []

    print(f"{'='*80}")
    print(f"Scenario Runner: {len(selected)} сценариев × {variations} вариаций")
    print(f"Level: {args.level} | Gate: {gate} | Judge: {'off' if args.no_judge else 'on'} | Model: {args.model} | Dry-run: {args.dry_run}")
    print(f"Seeds: {len(seeds)} | Metamorphic: {args.metamorphic}")
    print(f"{'='*80}")

    cfg = load_config()
    bothub = BothubClient(cfg.bothub_base, cfg.bothub_api_key, args.model)
    fake_cfg = Config(
        bot_token="test:fake_token",
        bothub_api_key="fake-key",
        bothub_base="http://fake.local/v1",
        llm_model="fake-model",
        max_concurrent_downloads=2,
        temp_ttl_minutes=30, user_rate_limit_per_hour=100,
        lastfm_api_key="",
    )

    gen = EventGenerator(bothub)
    judge = LLMJudge(bothub) if not args.no_judge else None
    verdicts: list[Verdict] = []

    try:
        for scenario in selected:
            print(f"\n── {scenario.id} [{scenario.category}] {scenario.jtbd} ──")
            print(f"   Вход: {scenario.input_desc[:120]}")

            # ==== Seed-based events (regression) ====
            events: list[GeneratedEvent] = []
            if use_seeds and seeds:
                for s in seeds:
                    if s.get("scenario") == scenario.id:
                        events.append(GeneratedEvent(
                            text=s["query"], variation=-1,
                            generation_time_ms=0.0,
                        ))
                if events:
                    print(f"   Seeds: {len(events)} фиксированных входов")

            # ==== Generation ====
            gen_count = max(1, variations - len(events))
            gen_events = await gen.generate(scenario, gen_count)
            events.extend(gen_events)
            print(f"   Сгенерировано: {len(gen_events)} новых + {len(events) - len(gen_events)} seeds = {len(events)} всего")
            if args.verbose:
                for e in events:
                    print(f"     [{e.variation}] {e.text[:100]}")

            if args.dry_run:
                for e in events:
                    v = Verdict(event=e, scenario_id=scenario.id, overall="SKIP")
                    verdicts.append(v)
                continue

            # ==== Execution ====
            for e in events:
                v = Verdict(event=e, scenario_id=scenario.id)

                # Gate 1
                if gate in ("1", "both"):
                    g1 = await run_gate1(e.text, fake_cfg)
                    v.gate1 = g1
                    v.det_checks = deterministic_checks(g1, scenario)

                # Gate 2
                if gate in ("2", "both") and ("2" in scenario.gate or gate2_all):
                    g2 = await run_gate2(e.text, bothub)
                    v.gate2 = g2

                # LLM-judge
                if judge and (gate in ("2", "both")):
                    score, reason, passed = await judge.evaluate(e, scenario, v.gate1, v.gate2)
                    v.llm_judge_score = score
                    v.llm_judge_reason = reason

                # Overall verdict
                det_ok = all(v.det_checks.values()) if v.det_checks else True
                judge_ok = v.llm_judge_score is None or v.llm_judge_score >= 0.6

                if v.gate1 and v.gate1.crashed:
                    v.overall = "FAIL"
                elif not det_ok:
                    v.overall = "FAIL"
                elif v.llm_judge_score is not None and v.llm_judge_score < 0.6:
                    v.overall = "FAIL"
                elif v.gate1 and not v.gate1.crashed:
                    v.overall = "PASS"
                else:
                    v.overall = "SKIP"

                # Determine the FAIL type
                fail_type = "none"
                if v.overall == "FAIL":
                    if v.gate2 and v.gate1:
                        if _is_dependency_flake(v.gate2, v.gate1):
                            fail_type = "dependency_flake"
                        else:
                            fail_type = "logic_fail"
                    else:
                        fail_type = "logic_fail"

                # Seed bank: store FAILs and low scores
                if v.overall == "FAIL" or (v.llm_judge_score is not None and v.llm_judge_score < 0.4):
                    actual_desc = ""
                    if v.gate2 and not v.gate2.crashed:
                        actual_desc = f"{v.gate2.best_title} | {v.gate2.best_channel}"
                    elif v.gate1:
                        actual_desc = " | ".join(v.gate1.texts[:2]) if v.gate1.texts else "no response"
                    _save_seed(
                        scenario.id, e.text, scenario.category,
                        scenario.expected, actual_desc,
                        v.llm_judge_score or 0.0,
                    )

                # Gate 2 artifacts
                if v.gate2 and not v.gate2.crashed:
                    _save_gate2_artifact(scenario.id, e.variation, e.text, v.gate2, fail_type)

                verdicts.append(v)

                # live output
                sym = {"PASS": "✅", "FAIL": "❌", "SKIP": "⊘"}.get(v.overall, "?")
                detail = ""
                if v.gate1:
                    detail += f" G1:{'CRASH' if v.gate1.crashed else f'{v.gate1.messages_sent}msg'}"
                if v.gate2:
                    detail += f" G2:{v.gate2.best_title[:40] if not v.gate2.crashed else 'CRASH'}"
                if v.llm_judge_score is not None:
                    detail += f" judge:{v.llm_judge_score:.2f}"
                if fail_type != "none":
                    detail += f" [{fail_type}]"
                if not v.det_checks:
                    failed = [k for k, ok in v.det_checks.items() if not ok]
                    detail += f" det-fail:{failed}"
                print(f"   {sym} [{e.variation}] {e.text[:80]}... {detail}")

    finally:
        await bothub.aclose()

    # ==== Metamorphic tests ====
    meta_verdicts: list[Verdict] = []
    if args.metamorphic and judge:
        meta_bothub = BothubClient(cfg.bothub_base, cfg.bothub_api_key, args.model)
        try:
            meta_verdicts = await run_metamorphic(METAMORPHIC_CASES, meta_bothub, judge)
        finally:
            await meta_bothub.aclose()

    # ==== Golden Traffic Suite ====
    golden_verdicts: list[Verdict] = []
    if args.golden and judge:
        golden_bothub = BothubClient(cfg.bothub_base, cfg.bothub_api_key, args.model)
        try:
            golden_verdicts = await run_golden_traffic(golden_bothub, judge, gate)
        finally:
            await golden_bothub.aclose()

    # ==== Record/Replay ====
    replay_results: list[Gate1Result] = []
    if args.replay:
        rrl = RecordReplayLayer(args.replay)
        updates = rrl.load()
        if updates:
            replay_results = await rrl.replay(updates, fake_cfg)

    # ==== Report ====
    n_pass = sum(1 for v in verdicts if v.overall == "PASS")
    n_fail = sum(1 for v in verdicts if v.overall == "FAIL")
    n_skip = sum(1 for v in verdicts if v.overall == "SKIP")

    print(f"\n{'='*80}")
    print(f"SCENARIO RUNNER REPORT")
    print(f"{'='*80}")
    print(f"Сценариев: {len(selected)} | Событий: {len(verdicts)} | Вариаций/сценарий: {variations}")
    print(f"Level: {args.level} | Gate: {gate} | Judge: {'off' if args.no_judge else 'on'}")

    # per scenario
    print(f"\n{'Scenario':<12} {'Cat':<12} {'Events':<8} {'PASS':<8} {'FAIL':<8} {'Notes'}")
    print("-" * 80)
    for sid in sorted(set(v.scenario_id for v in verdicts)):
        sv = [v for v in verdicts if v.scenario_id == sid]
        sp = sum(1 for v in sv if v.overall == "PASS")
        sf = sum(1 for v in sv if v.overall == "FAIL")
        notes = ""
        if sf > 0:
            fail_events = [v for v in sv if v.overall == "FAIL"]
            notes = "; ".join(f"{v.event.text[:50]}..." for v in fail_events[:2])
        print(f"{sid:<12} {sv[0].event.text[:30] if sv else '':<12} {len(sv):<8} {sp:<8} {sf:<8} {notes}")

    # FAIL-type statistics
    n_logic_fail = sum(1 for v in verdicts if v.overall == "FAIL"
                       and v.gate2 and v.gate1
                       and not _is_dependency_flake(v.gate2, v.gate1))
    n_dep_flake = sum(1 for v in verdicts if v.overall == "FAIL"
                      and v.gate2 and v.gate1
                      and _is_dependency_flake(v.gate2, v.gate1))
    n_crash = sum(1 for v in verdicts if v.overall == "FAIL"
                  and v.gate1 and v.gate1.crashed)

    seeds_count = len(_load_seeds())
    print(f"\nSCENARIO {'OK' if n_fail == 0 else 'FAILURES'}: PASS={n_pass} FAIL={n_fail} SKIP={n_skip}")
    if n_fail > 0:
        print(f"  logic_fail={n_logic_fail} dependency_flake={n_dep_flake} crash={n_crash}")
    print(f"Seed bank: {seeds_count} entries | Artifacts: {ARTIFACTS_DIR}")

    if meta_verdicts:
        n_meta_pass = sum(1 for v in meta_verdicts if v.overall == "PASS")
        n_meta_fail = sum(1 for v in meta_verdicts if v.overall == "FAIL")
        print(f"\nMETAMORPHIC: PASS={n_meta_pass} FAIL={n_meta_fail} (инварианты входных преобразований)")

    if golden_verdicts:
        n_gold_pass = sum(1 for v in golden_verdicts if v.overall == "PASS")
        n_gold_fail = sum(1 for v in golden_verdicts if v.overall == "FAIL")
        n_gold_warn = sum(1 for v in golden_verdicts if v.overall == "WARN")
        judge_agree = n_gold_pass / len(golden_verdicts) if golden_verdicts else 0
        print(f"\nGOLDEN TRAFFIC: PASS={n_gold_pass} FAIL={n_gold_fail} WARN={n_gold_warn} | Judge/reality agreement: {judge_agree:.0%}")

    if replay_results:
        n_replay_crash = sum(1 for r in replay_results if r.crashed)
        print(f"\nREPLAY: {len(replay_results)} updates, {n_replay_crash} crashes")


if __name__ == "__main__":
    asyncio.run(_main())
