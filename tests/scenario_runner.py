# Layer 3b-ext: Dual Judge (two models -> disagreement -> NEEDS REVIEW)
# ═══════════════════════════════════════════════════════════════

class DualJudge:
    """Two independent judges on different models. On disagreement — NEEDS REVIEW."""

    def __init__(self, primary: LLMJudge, secondary: LLMJudge | None = None,
                 disagreement_threshold: float = 0.3):
        self._primary = primary
        self._secondary = secondary
        self._threshold = disagreement_threshold

    async def evaluate(self, event: GeneratedEvent, scenario: ScenarioSpec,
                       g1: Gate1Result | None, g2: Gate2Result | None,
                       ) -> tuple[float, str, bool, str]:
        """Return (score, reason, pass, review_flag).

        review_flag: "ok" | "needs_review" | "disagreement"
        """
        score1, reason1, pass1 = await self._primary.evaluate(event, scenario, g1, g2)

        if self._secondary is None:
            return (score1, reason1, pass1, "ok")

        score2, reason2, pass2 = await self._secondary.evaluate(event, scenario, g1, g2)

        if abs(score1 - score2) > self._threshold or pass1 != pass2:
            # disagreement
            avg_score = (score1 + score2) / 2
            combined_reason = f"J1:{reason1} | J2:{reason2}"
            return (avg_score, combined_reason, avg_score >= 0.6, "disagreement")

        return (score1, reason1, pass1, "ok")

