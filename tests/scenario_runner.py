def _load_seeds() -> list[dict]:
    """Load the seed bank from file."""
    if not os.path.exists(SEEDS_PATH):
        return []
    try:
        with open(SEEDS_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data.get("seeds", [])
    except Exception:
        log.warning("Failed to load seeds.json")
        return []


def _save_seed(scenario_id: str, query: str, category: str, expected: str,
               actual: str, judge_score: float):
    """Add a provocative input to the seed bank."""
    seeds = _load_seeds()
    # duplicate check
    for s in seeds:
        if s.get("query") == query and s.get("scenario") == scenario_id:
            s["last_seen"] = datetime.now(timezone.utc).isoformat()
            s["judge_score"] = judge_score
            break
    else:
        seeds.append({
            "scenario": scenario_id,
            "query": query,
            "category": category,
            "expected": expected,
            "actual": actual,
            "judge_score": judge_score,
            "found": datetime.now(timezone.utc).isoformat(),
            "last_seen": datetime.now(timezone.utc).isoformat(),
        })
    try:
        os.makedirs(os.path.dirname(SEEDS_PATH), exist_ok=True)
        with open(SEEDS_PATH, "w", encoding="utf-8") as f:
            json.dump({"version": 1, "seeds": seeds}, f, ensure_ascii=False, indent=2)
        log.info("Seed bank updated: %s → %d seeds", scenario_id, len(seeds))
    except Exception:
        log.warning("Failed to write seeds.json")


