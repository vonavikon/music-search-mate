@dataclass
class RecordedUpdate:
    """A recorded Telegram update for replay."""
    update_json: dict
    timestamp: float  # unix time when received
    chat_id: int
    user_id: int
    text: str


class RecordReplayLayer:
    """Record and replay real Telegram updates.

    Record: intercepts update_json before process_update and stores it
            with timestamps to reproduce real dynamics.
    Replay: replays with delays, imitating real traffic
            (races, out-of-order, parallel dialogs).
    """

    def __init__(self, storage_path: str | None = None):
        self._path = storage_path or os.path.join(
            os.path.dirname(__file__), "recorded_updates.json",
        )
        self._records: list[RecordedUpdate] = []

    def record(self, update_json: dict, chat_id: int, user_id: int, text: str):
        """Record an update."""
        self._records.append(RecordedUpdate(
            update_json=update_json,
            timestamp=time.time(),
            chat_id=chat_id,
            user_id=user_id,
            text=text,
        ))

    def save(self):
        """Save the recorded updates to a file."""
        os.makedirs(os.path.dirname(self._path), exist_ok=True)
        data = {
            "source": "telegram-webhook",
            "recorded_at": datetime.now(timezone.utc).isoformat(),
            "updates": [
                {
                    "text": r.text,
                    "chat_id": r.chat_id,
                    "user_id": r.user_id,
                    "timestamp": r.timestamp,
                }
                for r in self._records
            ],
        }
        with open(self._path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        log.info("Recorded %d updates to %s", len(self._records), self._path)

    def load(self) -> list[dict]:
        """Load the recorded updates for replay."""
        if not os.path.exists(self._path):
            return []
        with open(self._path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data.get("updates", [])

    async def replay(self, updates: list[dict], fake_cfg: Config) -> list[Gate1Result]:
        """Replay the recorded updates with delays.

        Imitates real dynamics: parallel dialogs, quick repeats,
        out-of-order delivery.
        """
        results: list[Gate1Result] = []
        if not updates:
            return results

        print(f"  Replaying {len(updates)} recorded updates...")
        for i, u in enumerate(updates):
            text = u.get("text", "")
            chat_id = u.get("chat_id", 456)
            user_id = u.get("user_id", 123)

            # Imitate a real delay between messages (50-500ms)
            delay = 0.05 + (hash(text) % 45) / 100
            await asyncio.sleep(delay)

            update = _make_text_update(text, user_id=user_id, chat_id=chat_id)
            g1 = await run_gate1(text, fake_cfg)
            results.append(g1)

            sym = "❌" if g1.crashed else "✅"
            print(f"    [{i}] {sym} {g1.messages_sent}msg | {text[:60]}...")

        n_crash = sum(1 for r in results if r.crashed)
        n_ok = len(results) - n_crash
        print(f"  REPLAY: {n_ok}/{len(results)} OK, {n_crash} crashes")
        return results


